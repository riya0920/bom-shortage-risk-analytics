# 1. expedites
# ---------------------------------------------------------------------------

def expedite_options(base, drivers, mc) -> list[dict]:
    """For each gating part, what an expedite buys and what it costs.

    The number that decides an expedite is not the premium -- it is the premium
    against the MARGIN OF THE UNITS IT UNBLOCKS. A $4,000 air freight on a part
    that unblocks 12 units at $900 margin is obviously worth it; the same premium
    on a part that unblocks 12 units at $120 margin is not, and the reason
    materials meetings go badly is that the premium is visible on an invoice and
    the margin is not visible at all.
    """
    rows = []
    for d in drivers[:8]:
        part = d["part"]
        c = base.components.get(part)
        if c is None:
            continue
        s = base.suppliers[c.supplier_id]
        # Expedite compresses lead time; premium scales with how much you compress.
        for mode, compression, premium_mult in (("air freight", 0.45, 4.0),
                                                ("partial shipment", 0.70, 1.8),
                                                ("supplier overtime", 0.85, 1.25)):
            days_saved = s.lead_mean_days * (1 - compression)
            # Units unblocked: how many of the shortfall this part gates.
            gating_units = d["times_gating_in_sim"] / max(1, mc["n_sims"])
            premium = c.unit_cost * (premium_mult - 1.0) * max(50.0, gating_units * 10)
            rows.append({
                "part": part, "supplier": c.supplier_id, "mode": mode,
                "lead_mean_days": s.lead_mean_days,
                "days_saved": days_saved,
                "premium_usd": premium,
                "unit_cost": c.unit_cost,
                "single_sourced": c.single_sourced,
                "order_by_day": d["order_by_day"],
                "recovers_runway": bool(d["order_by_day"] + days_saved > 0),
            })
    return rows


