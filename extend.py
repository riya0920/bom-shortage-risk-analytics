def main() -> None:
    OUT.mkdir(exist_ok=True)
    if "--report-only" in sys.argv:
        prev = json.loads((OUT / "extensions.json").read_text())
        (ROOT / "docs" / "EXTENSIONS.md").write_text(report(prev), encoding="utf-8")
        print("re-rendered docs/EXTENSIONS.md")
        return

    t0 = time.perf_counter()
    quick = "--quick" in sys.argv
    base = supply.build()
    res: dict = {}

    print("1/4 Monte Carlo + expedite options ...", flush=True)
    mc = B.monte_carlo(base, n_sims=60 if quick else 200)
    drivers = B.shortage_drivers(base, mc)
    res["expedites"] = expedite_options(base, drivers, mc)
    res["drivers"] = drivers[:8]
    print(f"    {len(res['expedites'])} expedite options across "
          f"{len(res['drivers'])} gating parts", flush=True)

    print("2/4 multi-tier supplier risk ...", flush=True)
    st = build_subtier(base)
    res["subtier"] = {"n_tier2": st["n_tier2"],
                      "concentration": st["concentration"][:8]}
    res["hidden_single_source"] = hidden_single_source(base, st)[:6]
    top = st["concentration"][0]
    print(f"    top sub-tier {top['tier2']} sits behind {top['parts_behind_it']} "
          f"parts and {top['n_products_affected']} products", flush=True)

    print("3/4 genuine calibration against simulated futures ...", flush=True)
    res["calibration"] = calibrate_against_future(
        base, n_futures=25 if quick else 60, n_sims=60 if quick else 150)
    print(f"    P10-P90 contains the outcome "
          f"{res['calibration']['mean_inside_pct']:.1f}% of the time "
          f"(target 80%)", flush=True)

    print("4/4 the weekly materials pack ...", flush=True)
    res["pack"] = weekly_pack(base, mc, drivers, res)
    (OUT / "materials_review_pack.md").write_text(res["pack"], encoding="utf-8")
    res["wall_seconds"] = time.perf_counter() - t0

    (OUT / "extensions.json").write_text(json.dumps(res, indent=2, default=str))
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "EXTENSIONS.md").write_text(report(res), encoding="utf-8")
    print(f"\nwrote docs/EXTENSIONS.md and out/materials_review_pack.md "
          f"({res['wall_seconds']:.0f}s)")


def weekly_pack(base, mc, drivers, res) -> str:
    """The artifact the Monday meeting actually runs on, generated by code."""
    L = ["# Weekly Materials Review", "",
         "*Generated by `extend.py`. Every number traces to "
         "`out/extensions.json`.*", "",
         "## 1. Can we build the plan?", ""]
    L.append("| product | 13-week demand | P50 buildable | P10 | fill at P50 |")
    L.append("|---|---|---|---|---|")
    for p in base.products:
        f = mc["fan"][p]
        dem = float(np.sum(f["demand"]))
        p50 = float(np.sum(f["p50"]))
        p10 = float(np.sum(f["p10"]))
        L.append(f"| {p} | {dem:,.0f} | {p50:,.0f} | {p10:,.0f} | "
                 f"{100*p50/max(dem,1):.0f}% |")

    L += ["", "## 2. Top shortage drivers — action required", ""]
    L.append("| part | supplier | single source | first impact | order by | status |")
    L.append("|---|---|---|---|---|---|")
    for d in drivers[:6]:
        status = "**PAST DUE**" if d["already_too_late"] else "on track"
        L.append(f"| {d['part']} | {d['supplier']} | "
                 f"{'YES' if d['single_sourced'] else 'no'} | "
                 f"{('week ' + str(d['first_impact_week'])) if d['first_impact_week'] else '—'} | "
                 f"day {d['order_by_day']:+.0f} | {status} |")

    L += ["", "## 3. Recommended expedites", ""]
    L.append("| part | mode | days saved | premium | recovers runway? |")
    L.append("|---|---|---|---|---|")
    for e in res["expedites"][:8]:
        L.append(f"| {e['part']} | {e['mode']} | {e['days_saved']:.0f} | "
                 f"${e['premium_usd']:,.0f} | "
                 f"{'yes' if e['recovers_runway'] else 'no'} |")

    L += ["", "## 4. Sub-tier concentration", ""]
    L.append("| tier-2 source | tier-1 suppliers behind it | parts | products |")
    L.append("|---|---|---|---|")
    for c in res["subtier"]["concentration"][:5]:
        L.append(f"| {c['tier2']} | {c['tier1_suppliers']} | "
                 f"{c['parts_behind_it']} | {c['n_products_affected']} |")
    L += ["", "*Prepared for the Monday materials review. Items marked PAST DUE "
          "need a decision in this meeting, not next week.*", ""]
    return "\n".join(L)


def report(res: dict) -> str:
    L: list[str] = []
    A = L.append
    A("# DATA-3 extensions — generated by `extend.py`, not hand-edited\n")

    A("## 1. Expedites — what to DO about a shortage\n")
    A("The first build identified shortage drivers and stopped there. An expedite "
      "recommendation is what a materials manager is actually asking for, and the "
      "number that decides it is **not the premium** — it is the premium against "
      "the margin of the units it unblocks. That comparison is hard in practice "
      "for a structural reason: the premium arrives on an invoice and the margin "
      "is not visible from the materials system at all.\n")
    A("| part | supplier | mode | lead mean | days saved | premium | recovers runway? |")
    A("|---|---|---|---|---|---|---|")
    for e in res["expedites"][:12]:
        A(f"| {e['part']} | {e['supplier']} | {e['mode']} | "
          f"{e['lead_mean_days']:.0f} d | {e['days_saved']:.0f} d | "
          f"${e['premium_usd']:,.0f} | "
          f"{'**yes**' if e['recovers_runway'] else 'no'} |")
    rec = [e for e in res["expedites"] if e["recovers_runway"]]
    A(f"\n**{len(rec)} of {len(res['expedites'])} options actually recover the "
      "runway** — i.e. the days saved exceed the days already lost past the "
      "order-by date. The rest are money spent on a part that will still be late, "
      "which is the expedite decision people get wrong most often: air freight on "
      "a part that needed ordering six weeks ago buys a faster arrival of "
      "something that is still after the line stops.")

    A("\n## 2. Multi-tier risk — the concentration nobody sees\n")
    A("**Dual-sourcing a part is worthless if both sources buy from the same "
      "sub-tier.** This is the failure that took out automotive semiconductors and "
      "aerospace castings repeatedly: the risk register said \"dual sourced\" and "
      "the dependency graph said otherwise, because nobody had the second tier.\n")
    A("| tier-2 source | tier-1 suppliers behind it | parts exposed | products affected |")
    A("|---|---|---|---|")
    for c in res["subtier"]["concentration"]:
        A(f"| {c['tier2']} | {c['tier1_suppliers']} | {c['parts_behind_it']} | "
          f"{c['n_products_affected']} ({', '.join(c['products_affected'])}) |")
    top = res["subtier"]["concentration"][0]
    A(f"\n**{top['tier2']} sits behind {top['tier1_suppliers']} tier-1 suppliers, "
      f"{top['parts_behind_it']} parts, and {top['n_products_affected']} of the "
      "product line.** A single-tier risk score cannot see that number, because at "
      "tier 1 those parts are spread across many independent-looking vendors.\n")
    if res.get("hidden_single_source"):
        A("Tier-1 suppliers a buyer would treat as alternatives, that in fact "
          "converge:\n")
        A("| tier-2 | tier-1 suppliers sharing it | parts exposed |")
        A("|---|---|---|")
        for h in res["hidden_single_source"]:
            A(f"| {h['tier2']} | {h['tier1_count']} ({', '.join(h['tier1_suppliers'])}) | "
              f"{h['parts_exposed']} |")
    A("\n**Honest scope:** the tier-2 mapping is *generated*, not discovered. In "
      "reality it is the hardest data in this whole project to obtain — suppliers "
      "treat their own sources as confidential, and the mapping is assembled from "
      "questionnaires, customs records and industry knowledge, then goes stale. "
      "The analysis here shows what the data buys once you have it; getting it is "
      "the actual work and it is not a modelling problem.")

    c = res["calibration"]
    A("\n## 3. Calibration — the real version\n")
    A("RESULTS.md §2 checked what fraction of simulations fell below their own "
      "P50, and said outright that this verifies arithmetic rather than the model. "
      "This is the honest test: draw "
      f"**{c['n_futures']} independent futures** from the generative process, "
      "treat each as what actually happened, and ask how often the forecast fan "
      f"(built from {c['n_sims_in_fan']} simulations) contained it.\n")
    A("| product | % inside P10–P90 | % below P10 | % above P90 | target |")
    A("|---|---|---|---|---|")
    for r in c["per_product"]:
        A(f"| {r['product']} | **{r['pct_inside_p10_p90']:.1f}%** | "
          f"{r['pct_below_p10']:.1f}% | {r['pct_above_p90']:.1f}% | 80% |")
    m = c["mean_inside_pct"]
    A(f"\n**Mean coverage: {m:.1f}% against a target of 80%.**\n")
    if m > 90:
        A("The band is **too wide**. An interval that contains the outcome far more "
          "often than advertised is not conservative-and-therefore-safe: it is a "
          "forecast nobody will plan against, because the P10 stops being a "
          "meaningful floor. The likely cause is that the fan and the futures are "
          "drawn from the same lead-time distributions, so the only variation the "
          "fan sees is the variation it was built from — a real fan also has to "
          "carry parameter uncertainty, which would widen the *true* outcome spread "
          "rather than the predicted one.")
    elif m < 70:
        A("The band is **too narrow** — the plan is being presented as more certain "
          "than it is, which is the more dangerous direction. A materials manager "
          "who commits to a P10 that is breached a third of the time will stop "
          "believing the fan after the second occasion.")
    else:
        A("Coverage is close to nominal, which is what makes the P10 usable as a "
          "commitment floor rather than a decoration.")
    A("\nThis is still a calibration against *my own generator*, and that limit is "
      "irreducible without real receipt history: the futures and the fan share a "
      "data-generating process, so what is verified is internal consistency of the "
      "propagation, not that supplier lead times behave this way.")

    A("\n## 4. The weekly materials pack\n")
    A("Generated to `out/materials_review_pack.md` — the artifact the Monday "
      "meeting runs on, produced by code rather than assembled by hand at 7 a.m. "
      "Four sections: can we build the plan, top shortage drivers with order-by "
      "dates, recommended expedites with costs, and sub-tier concentration.\n")
    A("The design rule for this document is that **every row implies an action or "
      "it does not belong**. A materials pack that reports status without naming "
      "the decision is the thing that makes the meeting an hour long and the "
      "decisions late.")

    A("\n---\n*Regenerate with `python extend.py`.*")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    main()
