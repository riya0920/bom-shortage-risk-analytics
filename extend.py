# 2. multi-tier
# ---------------------------------------------------------------------------

def build_subtier(base, seed: int = 31) -> dict:
    """Assign each tier-1 supplier a tier-2 source, and find the concentrations.

    THE POINT: dual-sourcing a part is worthless if both sources buy from the same
    sub-tier. This is the failure that took out automotive semiconductors and
    aerospace castings repeatedly -- the risk register said "dual sourced" and the
    dependency graph said otherwise, because nobody had the second tier.
    """
    rng = np.random.default_rng(seed)
    tier2 = [f"T2-{i+1:02d}" for i in range(12)]
    # Deliberately skewed: a few sub-tier suppliers serve many tier-1s.
    weights = np.array([6.0, 5.0, 4.0] + [1.0] * (len(tier2) - 3))
    weights = weights / weights.sum()
    mapping = {sid: str(rng.choice(tier2, p=weights)) for sid in base.suppliers}

    # For each PART, which tier-2 sources does it ultimately depend on?
    part_t2: dict[str, set] = {}
    for part, c in base.components.items():
        if c.level == 2 and c.supplier_id:
            part_t2.setdefault(part, set()).add(mapping[c.supplier_id])

    # Concentration: how many parts, and how many products, sit behind each T2.
    req = supply.unit_requirements(base)
    t2_parts: dict[str, list] = {}
    for part, s in part_t2.items():
        for t in s:
            t2_parts.setdefault(t, []).append(part)

    rows = []
    for t, parts in sorted(t2_parts.items(), key=lambda kv: -len(kv[1])):
        products = {p for p in base.products if any(pt in req[p] for pt in parts)}
        rows.append({
            "tier2": t, "tier1_suppliers": sum(1 for v in mapping.values() if v == t),
            "parts_behind_it": len(parts),
            "products_affected": sorted(products),
            "n_products_affected": len(products),
        })
    return {"mapping": mapping, "concentration": rows,
            "n_tier2": len(t2_parts)}


def hidden_single_source(base, subtier) -> list[dict]:
    """Parts that look multi-sourced at tier 1 but converge at tier 2.

    Here every part has ONE tier-1 supplier, so the honest version of this check
    is at the SUPPLIER level: which tier-1 suppliers a buyer would treat as
    independent alternatives, but which share a sub-tier.
    """
    mapping = subtier["mapping"]
    by_t2: dict[str, list] = {}
    for sid, t2 in mapping.items():
        by_t2.setdefault(t2, []).append(sid)
    out = []
    for t2, sids in sorted(by_t2.items(), key=lambda kv: -len(kv[1])):
        if len(sids) < 2:
            continue
        parts = [p for p, c in base.components.items()
                 if c.level == 2 and c.supplier_id in sids]
        out.append({"tier2": t2, "tier1_count": len(sids),
                    "tier1_suppliers": sorted(sids)[:6],
                    "parts_exposed": len(parts)})
    return out


